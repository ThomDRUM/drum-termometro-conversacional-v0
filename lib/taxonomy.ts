// ── Structured output types ───────────────────────────────────

export type PhaseResult = {
  name: Phase;
  short_description: string;
  personal_connection: string; // AI-generated: how THIS person's story maps to the phase
  confidence: number;          // 0–1
  evidence: string[];
};

export type PathwayResult = {
  name: Pathway;
  short_description: string;
  personal_fit: string;        // AI-generated: why THIS pathway fits this person specifically
  confidence: number;          // 0–1
  evidence: string[];
};

export type ClaritycriterionResult = {
  score_0_to_2: 0 | 1 | 2;
  evidence: string;
};

export type ClarityResult = {
  score_1_to_5: 1 | 2 | 3 | 4 | 5;
  label: ClarityLabel;
  total_points_0_to_10: number;
  criteria: {
    direction_naming:    ClaritycriterionResult;
    speech_coherence:    ClaritycriterionResult;
    own_criteria:        ClaritycriterionResult;
    concrete_movement:   ClaritycriterionResult;
    ambiguity_tolerance: ClaritycriterionResult;
  };
};

export type TensionResult = {
  name: Tension;
  short_description: string;
  personal_detail: string;     // AI-generated: specific manifestation in this person's situation
  confidence: number;          // 0–1
  evidence: string[];
};

export type Action = {
  type: ActionType;
  title: string;
  description: string;
  why_this_action: string;
  timeframe: string;
};

export type DiagnosticoMetadata = {
  anxiety_score_1_to_5: number | null;
  conversation_duration_seconds: number | null;
  mentioned_people: string[];
  mentioned_projects: string[];
  raw_summary: string;
};

