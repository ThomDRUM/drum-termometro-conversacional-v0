// ── Clarity labels ───────────────────────────────────────────
// Derived from total_points_0_to_10:
// 0–2 → Difusa | 3–4 → Emergente | 5–6 → Em construção
// 7–8 → Clara  | 9–10 → Muito clara

export const CLARITY_LABELS = [
  "Difusa",
  "Emergente",
  "Em construção",
  "Clara",
  "Muito clara",
] as const;

export type ClarityLabel = (typeof CLARITY_LABELS)[number];

export function clarityLabelFromScore(points: number): ClarityLabel {
  if (points <= 2) return "Difusa";
  if (points <= 4) return "Emergente";
  if (points <= 6) return "Em construção";
  if (points <= 8) return "Clara";
  return "Muito clara";
}

export function clarityScoreFromPoints(points: number): 1 | 2 | 3 | 4 | 5 {
  if (points <= 2) return 1;
  if (points <= 4) return 2;
  if (points <= 6) return 3;
  if (points <= 8) return 4;
  return 5;
}

